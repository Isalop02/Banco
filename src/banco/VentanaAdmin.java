    private void btnEliminarClienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarClienteActionPerformed
        // TODO add your handling code here:
        try {
    int id = Integer.parseInt(txtIdCliente.getText());
    int respuesta = JOptionPane.showConfirmDialog(this, "¿Seguro que desea eliminar el cliente?");
    if (respuesta != JOptionPane.YES_OPTION) return;

    Connection con = Conexion.conectar();
    PreparedStatement ps = con.prepareStatement("DELETE FROM clientes WHERE id = ? AND estado = 0");
    ps.setInt(1, id);
    int filas = ps.executeUpdate();
    con.close();

    if (filas > 0) JOptionPane.showMessageDialog(this, "Cliente eliminado");
    else JOptionPane.showMessageDialog(this, "No existe o está ocupado");
    listarClientes();
} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
}
    }//GEN-LAST:event_btnEliminarClienteActionPerformed

