    // Llena la tabla de clientes con el resultado de una consulta
private void llenarTablaClientes(ResultSet rs) throws Exception {
    DefaultTableModel modelo = (DefaultTableModel) tablaClientes.getModel();
    modelo.setRowCount(0); // borra lo que había
    while (rs.next()) {
        modelo.addRow(new Object[]{
            rs.getInt("id"), rs.getString("nombre"), rs.getString("apellido"),
            rs.getString("telefono"), rs.getString("ciudad"), rs.getInt("ncuenta"),
            rs.getDouble("saldo"), rs.getInt("estado")
        });
    }
}

// Muestra todos los clientes
private void listarClientes() {
    try {
        Connection con = Conexion.conectar();
        ResultSet rs = con.createStatement().executeQuery("SELECT * FROM clientes");
        llenarTablaClientes(rs);
        con.close();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
}

