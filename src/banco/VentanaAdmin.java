    private void btnRetirarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRetirarActionPerformed
        // TODO add your handling code here:
        try {
    int id = Integer.parseInt(txtIdCliente.getText());
    double monto = Double.parseDouble(txtMonto.getText());
    if (monto <= 0) {
        JOptionPane.showMessageDialog(this, "El monto debe ser mayor a 0");
        return;
    }
    if (!Conexion.bloquear("clientes", id)) {
        JOptionPane.showMessageDialog(this, "El cliente no existe o está ocupado");
        return;
    }
    Connection con = Conexion.conectar();
    PreparedStatement ps = con.prepareStatement(
        "UPDATE clientes SET saldo = saldo - ? WHERE id = ? AND saldo >= ?");
    ps.setDouble(1, monto);
    ps.setInt(2, id);
    ps.setDouble(3, monto);
    int filas = ps.executeUpdate();
    con.close();
    Conexion.liberar("clientes", id);

    if (filas > 0) JOptionPane.showMessageDialog(this, "Retiro realizado");
    else JOptionPane.showMessageDialog(this, "Saldo insuficiente");
    listarClientes();
} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
}
    }//GEN-LAST:event_btnRetirarActionPerformed

